import { useQuery } from "@tanstack/react-query";
import { useParams } from "@tanstack/react-router";
import type { endpoints } from "@/api/endpoints";
import { queries } from "@/api/queries";
import { PageHeader } from "@/components/page-header";
import { Button } from "@/components/ui/button";
import { Card, CardHeader } from "@/components/ui/card";
import { Pill } from "@/components/ui/pill";
import { EmptyState, QueryView } from "@/components/ui/states";
import { ProductGraph } from "./product-graph";

type Knowledge = Awaited<ReturnType<typeof endpoints.knowledge>>;

export function KnowledgePage() {
  const { projectId } = useParams({ from: "/p/$projectId/knowledge" });
  const knowledge = useQuery(queries.knowledge(projectId));
  return (
    <QueryView query={knowledge}>
      {(data) => <KnowledgeView projectId={projectId} data={data} />}
    </QueryView>
  );
}

function KnowledgeView({ projectId, data }: { projectId: string; data: Knowledge }) {
  const withRules = data.adrs.filter((a) => a.rules > 0).length;
  return (
    <>
      <PageHeader
        title={`${projectId} · Knowledge`}
        subtitle={`Product graph · ${data.adrs.length} ADRs · ${data.graph.nodes.length} graph nodes`}
        actions={
          <>
            <Button>Regenerate code graph</Button>
            <Button variant="primary">New ADR</Button>
          </>
        }
      />
      <Card>
        <CardHeader
          title="Product graph"
          meta="goals → features → ADRs → tickets → modules · click a node to trace it"
        />
        {data.graph.nodes.length ? (
          <ProductGraph nodes={data.graph.nodes} edges={data.graph.edges} />
        ) : (
          <div className="px-4 pb-4">
            <EmptyState
              title="No product graph yet"
              hint="It is generated by the init interview and updated after each merge."
            />
          </div>
        )}
      </Card>

      <div className="mt-4 grid grid-cols-[minmax(0,1fr)_420px] gap-4">
        <Card>
          <CardHeader title="ADRs" meta={`${data.adrs.length} · ${withRules} with rules`} />
          <ul className="px-4 pb-2">
            {data.adrs.map((adr) => (
              <li
                key={adr.id}
                className="grid grid-cols-[minmax(0,1fr)_minmax(0,200px)_80px_auto] items-center gap-3 border-border-subtle border-b py-3.5 last:border-0"
              >
                <span className="text-body text-fg">
                  {adr.id} {adr.title}
                </span>
                <span className="truncate font-mono text-caption text-fg-secondary">
                  {adr.path}
                </span>
                <span className="font-mono text-caption text-fg-secondary">
                  {adr.rules ? `${adr.rules} rule${adr.rules > 1 ? "s" : ""}` : "—"}
                </span>
                <Pill tone={adr.status.tone} className="justify-self-end">
                  {adr.status.label}
                </Pill>
              </li>
            ))}
          </ul>
        </Card>
        <Card className="self-start">
          <CardHeader title="Rule violations" meta={data.checks.ref} />
          <ul className="space-y-2 px-4 pb-4">
            {data.checks.violations.length === 0 ? (
              <li className="text-body text-fg-secondary">No violations on the default branch.</li>
            ) : null}
            {data.checks.violations.map((v) => (
              <li key={`${v.adr}-${v.location}`} className="rounded-control bg-raised p-3">
                <div className="flex items-center gap-2">
                  <Pill tone={v.level === "error" ? "red" : "amber"}>{v.level}</Pill>
                  <span className="font-mono text-caption text-fg-secondary">{v.adr}</span>
                </div>
                <div className="mt-2 font-mono text-label text-fg">{v.location}</div>
                <div className="mt-1.5 text-body text-fg-secondary">{v.message}</div>
                <div className="mt-1.5 text-caption text-fg-muted">{v.note}</div>
              </li>
            ))}
          </ul>
        </Card>
      </div>
    </>
  );
}
