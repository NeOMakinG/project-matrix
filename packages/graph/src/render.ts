import { type CodeGraph, folderOf } from "./code";

const table = (head: string[], rows: string[][]) =>
  rows.length === 0
    ? "_None._\n"
    : `| ${head.join(" | ")} |\n| ${head.map(() => "---").join(" | ")} |\n${rows
        .map((r) => `| ${r.join(" | ")} |`)
        .join("\n")}\n`;

/** Human summary of the code graph, committed as `.matrix/graph/GRAPH.md`. */
export function renderGraphMarkdown(g: CodeGraph): string {
  const internal = g.modules.flatMap((m) =>
    m.imports.filter((i) => i.target).map((i) => ({ from: m.path, to: i.target as string })),
  );

  const folders = new Map<string, { modules: number; out: Set<string>; in: Set<string> }>();
  const folder = (f: string) => {
    let entry = folders.get(f);
    if (!entry) {
      entry = { modules: 0, out: new Set(), in: new Set() };
      folders.set(f, entry);
    }
    return entry;
  };
  for (const m of g.modules) folder(folderOf(m.path)).modules++;
  const folderEdges = new Map<string, number>();
  for (const e of internal) {
    const a = folderOf(e.from);
    const b = folderOf(e.to);
    if (a === b) continue;
    folder(a).out.add(b);
    folder(b).in.add(a);
    const key = `${a}\u0000${b}`;
    folderEdges.set(key, (folderEdges.get(key) ?? 0) + 1);
  }

  const inbound = new Map<string, number>();
  for (const e of internal) inbound.set(e.to, (inbound.get(e.to) ?? 0) + 1);
  const mostImported = [...inbound.entries()]
    .sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0]))
    .slice(0, 15);

  return `# Code graph

Generated by \`matrix graph\`. Do not edit by hand: \`matrix graph --check\` fails CI when this file or \`code.json\` is stale.

${g.modules.length} modules, ${internal.length} internal imports, ${g.packages.length} external packages, ${g.cycles.length} import cycles.

## Folders

${table(
  ["Folder", "Modules", "Imports from", "Imported by"],
  [...folders.entries()]
    .sort((a, b) => a[0].localeCompare(b[0]))
    .map(([f, v]) => [
      `\`${f}\``,
      String(v.modules),
      [...v.out].sort().join(", ") || "-",
      [...v.in].sort().join(", ") || "-",
    ]),
)}
## Folder dependencies

${table(
  ["From", "To", "Imports"],
  [...folderEdges.entries()]
    .map(([k, n]) => {
      const [a = "", b = ""] = k.split("\u0000");
      return [`\`${a}\``, `\`${b}\``, String(n)];
    })
    .sort(
      (x, y) => (x[0] ?? "").localeCompare(y[0] ?? "") || (x[1] ?? "").localeCompare(y[1] ?? ""),
    ),
)}
## Most imported modules

${table(
  ["Module", "Importers"],
  mostImported.map(([p, n]) => [`\`${p}\``, String(n)]),
)}
## External packages

${table(
  ["Package", "Importing modules"],
  g.packages.map((p) => [`\`${p.name}\``, String(p.importers)]),
)}
## Import cycles

${g.cycles.length === 0 ? "_None._\n" : g.cycles.map((c, i) => `${i + 1}. ${c.map((p) => `\`${p}\``).join(" → ")}`).join("\n")}
`;
}
