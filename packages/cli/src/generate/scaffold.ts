import type { MatrixConfig } from "@matrix/config";
import { lintPreset } from "@matrix/rules";
import { apiFiles } from "./api";
import { ciWorkflow } from "./ci";
import type { Files } from "./docs";
import { md } from "./escape";
import { pick } from "./versions";
import { webFiles } from "./web";

export const packageName = (name: string) =>
  name
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "") || "app";

export function scaffoldFiles(c: MatrixConfig): { files: Files; warnings: string[] } {
  const warnings: string[] = [];
  const pkg = packageName(c.business.name);
  const fe = c.frontend;
  const lint = lintPreset(c);
  let files: Files = {
    "package.json": `${JSON.stringify(
      {
        name: pkg,
        private: true,
        type: "module",
        workspaces: ["apps/*"],
        scripts: {
          typecheck: "bun run --filter '*' typecheck",
          test: "bun run --filter '*' test",
          ...lint.scripts,
        },
        devDependencies: pick(["typescript", ...lint.devDependencies]),
      },
      null,
      2,
    )}\n`,
    "tsconfig.base.json": `${JSON.stringify(
      {
        compilerOptions: {
          target: "ES2023",
          module: "ESNext",
          moduleResolution: "Bundler",
          strict: true,
          noUncheckedIndexedAccess: true,
          skipLibCheck: true,
          isolatedModules: true,
          verbatimModuleSyntax: true,
          noEmit: true,
        },
      },
      null,
      2,
    )}\n`,
    ".gitignore": "node_modules/\ndist/\n.env\n.env.*\n",
    ...lint.files,
    ".github/workflows/ci.yml": ciWorkflow(c),
    "README.md": `# ${md(c.business.name)}

${md(c.business.problem)}

Generated by Project Matrix (\`matrix init\`). Decisions live in \`docs/adr/\`, the domain in \`CONTEXT.md\`, the backlog in the ${c.process.tickets} ticket system.
`,
  };

  if (fe?.framework === "react") {
    if (fe.bundler !== "vite") {
      warnings.push(
        `Web scaffold only supports Vite today; ${fe.bundler} was chosen, so apps/web was not generated.`,
      );
    } else {
      files = { ...files, ...webFiles(c, fe, pkg) };
    }
  } else if (fe) {
    warnings.push(`No scaffold pack for ${fe.name} yet; apps/web was not generated.`);
  }

  const api = apiFiles(c, pkg);
  warnings.push(...api.warnings);
  files = { ...files, ...api.files };
  return { files, warnings };
}
