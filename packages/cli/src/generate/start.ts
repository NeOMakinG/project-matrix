import type { MatrixConfig } from "@matrix/config";
import type { Files } from "./docs";
import { jsxText, tsString } from "./escape";
import { headersLiteral } from "./headers";
import { type ReactStack, reactLibraryDeps } from "./react-libs";
import { pick } from "./versions";

const json = (v: unknown) => `${JSON.stringify(v, null, 2)}\n`;

/** TanStack Start (full-stack, file routes, server functions) in apps/web. */
export function startFiles(c: MatrixConfig, fe: ReactStack, pkg: string): Files {
  const tailwind = fe.styling === "tailwind";
  const query = fe.data === "tanstack-query";
  const deps = [
    "@tanstack/react-start",
    "@tanstack/react-router",
    "react",
    "react-dom",
    ...reactLibraryDeps(c, fe),
  ];
  const dev = ["typescript", "@types/react", "@types/react-dom", "@types/node", "vitest"];
  if (tailwind) dev.push("tailwindcss", "@tailwindcss/vite");
  if (fe.e2e === "playwright") dev.push("@playwright/test");

  const files: Files = {
    "apps/web/package.json": json({
      name: `${pkg}-web`,
      private: true,
      type: "module",
      scripts: {
        dev: "vite dev",
        build: "vite build",
        start: "node .output/server/index.mjs",
        // The route tree is generated by the Start plugin, so typecheck after a build.
        typecheck: "vite build --logLevel error && tsc -p tsconfig.json --noEmit",
        test: "vitest run --passWithNoTests",
      },
      dependencies: pick(deps),
      // Start tracks Vite 8 / plugin-react 6 ahead of the Vite SPA scaffold.
      devDependencies: { ...pick(dev), vite: "^8.0.0", "@vitejs/plugin-react": "^6.0.0" },
    }),
    "apps/web/tsconfig.json": json({
      extends: "../../tsconfig.base.json",
      compilerOptions: {
        jsx: "react-jsx",
        lib: ["ES2023", "DOM", "DOM.Iterable"],
        types: ["vite/client"],
        paths: { "~/*": ["./src/*"] },
      },
      include: ["src", "vite.config.ts"],
    }),
    "apps/web/vite.config.ts": `import { tanstackStart } from "@tanstack/react-start/plugin/vite";
import viteReact from "@vitejs/plugin-react";
${tailwind ? 'import tailwindcss from "@tailwindcss/vite";\n' : ""}import { defineConfig } from "vite";

export default defineConfig({
  resolve: { tsconfigPaths: true },
  plugins: [${tailwind ? "tailwindcss(), " : ""}tanstackStart({ srcDirectory: "src" }), viteReact()],
});
`,
    "apps/web/src/start.ts": `import { createMiddleware, createStart } from "@tanstack/react-start";

const securityHeaders: Record<string, string> = ${headersLiteral("")};

/** Sends the security headers on every response (pages and server functions). */
const securityHeadersMiddleware = createMiddleware({ type: "request" }).server(async ({ next }) => {
  const result = await next();
  for (const [name, value] of Object.entries(securityHeaders)) result.response.headers.set(name, value);
  return result;
});

export const startInstance = createStart(() => ({
  requestMiddleware: [securityHeadersMiddleware],
}));
`,
    "apps/web/src/router.tsx": `import { createRouter } from "@tanstack/react-router";
import { routeTree } from "./routeTree.gen";

export function getRouter() {
  return createRouter({ routeTree, defaultPreload: "intent", scrollRestoration: true });
}
`,
    "apps/web/src/routes/__root.tsx": `/// <reference types="vite/client" />
${query ? 'import { QueryClient, QueryClientProvider } from "@tanstack/react-query";\n' : ""}import { createRootRoute, HeadContent, Outlet, Scripts } from "@tanstack/react-router";
import type { ReactNode } from "react";${query ? '\nimport { useState } from "react";' : ""}
${tailwind ? 'import appCss from "~/styles.css?url";\n' : ""}
export const Route = createRootRoute({
  head: () => ({
    meta: [
      { charSet: "utf-8" },
      { name: "viewport", content: "width=device-width, initial-scale=1" },
      { title: ${tsString(c.business.name)} },
    ],${tailwind ? '\n    links: [{ rel: "stylesheet", href: appCss }],' : ""}
  }),
  component: RootComponent,
  shellComponent: RootDocument,
});

function RootComponent() {${query ? "\n  const [client] = useState(() => new QueryClient());\n  return (\n    <QueryClientProvider client={client}>\n      <Outlet />\n    </QueryClientProvider>\n  );" : "\n  return <Outlet />;"}
}

function RootDocument({ children }: { children: ReactNode }) {
  return (
    <html lang="en">
      <head>
        <HeadContent />
      </head>
      <body>
        {children}
        <Scripts />
      </body>
    </html>
  );
}
`,
    "apps/web/src/routes/index.tsx": `import { createFileRoute } from "@tanstack/react-router";

export const Route = createFileRoute("/")({ component: Home });

function Home() {
  return (
    <main${tailwind ? ' className="mx-auto max-w-2xl p-8"' : ""}>
      <h1>${jsxText(c.business.name)}</h1>
      <p>${jsxText(c.business.valueProposition)}</p>
    </main>
  );
}
`,
    "apps/web/.gitignore": ".output/\n.tanstack/\n",
  };
  if (tailwind) files["apps/web/src/styles.css"] = '@import "tailwindcss";\n';
  return files;
}
