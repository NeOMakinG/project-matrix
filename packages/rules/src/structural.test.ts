import { describe, expect, test } from "vitest";
import { checkCapability, isGeneratedGo, parseGoImports } from "./structural";

describe("parseGoImports", () => {
  test("single, aliased, dot, blank, raw-string and grouped imports", () => {
    const src = [
      "package x",
      'import "database/sql"',
      "import db `github.com/jackc/pgx/v5`",
      "import (",
      '\tf "fmt"',
      "\t. `github.com/lib/pq` // driver",
      '\t_ "embed"; "os"',
      '\t/* "not/an/import" */',
      ")",
      'func f() { s := "import \\"x\\"" }',
    ].join("\n");
    const paths = parseGoImports(src).map((i) => i.path);
    expect(paths).toEqual([
      "database/sql",
      "github.com/jackc/pgx/v5",
      "fmt",
      "github.com/lib/pq",
      "embed",
      "os",
    ]);
  });

  test("commented-out imports are ignored and line numbers are kept", () => {
    const src = 'package x\n// import "database/sql"\n/*\nimport "log"\n*/\nimport "net/http"\n';
    expect(parseGoImports(src)).toEqual([{ path: "net/http", line: 6 }]);
  });

  test("escaped characters in interpreted strings are decoded", () => {
    expect(parseGoImports('package x\nimport "database\\u002fsql"\n')[0]?.path).toBe(
      "database/sql",
    );
  });

  test("generated marker must be Go's exact header form", () => {
    expect(isGeneratedGo("// Code generated by sqlc. DO NOT EDIT.\npackage db\n")).toBe(true);
    expect(isGeneratedGo("package db\n// Code generated maybe\n")).toBe(false);
  });
});

describe("checkCapability", () => {
  const allow = ["core:default", "updater:default"];
  const perms = (permissions: unknown[]) =>
    checkCapability(JSON.stringify({ identifier: "x", windows: ["main"], permissions }), allow);

  test("least-privilege capability passes", () => {
    expect(perms(["core:default", "updater:default"])).toEqual([]);
  });

  test.each([
    ["shell:allow-execute"],
    ["shell:allow-spawn"],
    ["shell:default"],
    ["fs:read-all"],
    ["fs:allow-read-all"],
    ["fs:default"],
    ["fs:allow-home-read-recursive"],
    ["process:allow-restart"],
    ["FS:READ-ALL"],
    [" shell:allow-execute "],
  ])("refuses dangerous permission %s", (id) => {
    expect(perms([id]).length).toBeGreaterThan(0);
  });

  test("escaped identifiers are decoded before matching", () => {
    const text = '{"permissions":["\\u0073hell:allow-execute"]}';
    expect(
      checkCapability(text, allow)
        .map((f) => f.message)
        .join(),
    ).toContain("shell:allow-execute");
  });

  test("permissions outside the allow-list are refused", () => {
    expect(perms(["http:default"])[0]?.message).toContain("not on the ADR allow-list");
  });

  test.each([["$HOME/**"], ["**"], ["/"], ["$APPDATA/../../etc"], ["$DESKTOP/*"]])(
    "refuses broad scope %s",
    (path) => {
      const found = perms([{ identifier: "core:default", allow: [{ path }] }]);
      expect(found.some((f) => f.message.includes("reaches outside"))).toBe(true);
    },
  );

  test("app-directory scopes are fine", () => {
    expect(perms([{ identifier: "core:default", allow: [{ path: "$APPDATA/**" }] }])).toEqual([]);
  });

  test("invalid JSON fails closed", () => {
    expect(checkCapability("{ not json", allow)[0]?.message).toContain("not valid JSON");
  });
});
