import { spawnSync } from "node:child_process";
import { mkdir, mkdtemp, readdir, readFile, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { describe, expect, test } from "vitest";
import { verifySqlc } from "./sqlc";
import { sandboxTool } from "./toolchain";

const hasSqlc = spawnSync("sqlc", ["version"]).status === 0;
const hasSandbox = sandboxTool("sqlc", ["version"], tmpdir(), tmpdir()).status === 0;

const CONFIG = `version: "2"
sql:
  - engine: postgresql
    schema: internal/db/schema.sql
    queries: internal/db/queries.sql
    gen:
      go:
        package: db
        out: internal/db
        sql_package: pgx/v5
`;

async function module(): Promise<{ root: string; files: () => Promise<string[]> }> {
  const root = await mkdtemp(join(tmpdir(), "matrix-sqlc-test-"));
  await mkdir(join(root, "svc/internal/db"), { recursive: true });
  await writeFile(join(root, "svc/sqlc.yaml"), CONFIG);
  await writeFile(
    join(root, "svc/internal/db/schema.sql"),
    "CREATE TABLE t (id bigint primary key);\n",
  );
  await writeFile(
    join(root, "svc/internal/db/queries.sql"),
    "-- name: GetT :one\nSELECT id FROM t WHERE id = $1;\n",
  );
  const files = async () =>
    (await readdir(join(root, "svc/internal/db")))
      .map((f) => `svc/internal/db/${f}`)
      .concat("svc/sqlc.yaml");
  return { root, files };
}

describe.runIf(hasSqlc && hasSandbox)(
  "sqlc output verified by regeneration (round 2, P1-C)",
  () => {
    test("untouched sqlc output passes", async () => {
      const m = await module();
      expect(spawnSync("sqlc", ["generate"], { cwd: join(m.root, "svc") }).status).toBe(0);
      expect(await verifySqlc(m.root, await m.files())).toEqual([]);
    });

    test("a hand-written file with a forged sqlc header is flagged", async () => {
      const m = await module();
      spawnSync("sqlc", ["generate"], { cwd: join(m.root, "svc") });
      await writeFile(
        join(m.root, "svc/internal/db/fakegen.go"),
        '// Code generated by sqlc. DO NOT EDIT.\npackage db\n\nimport "database/sql"\n\nfunc Raw(d *sql.DB, q string) { d.Query(q) }\n',
      );
      await writeFile(
        join(m.root, "svc/internal/db/late.go"),
        'package db\n// Code generated by sqlc. DO NOT EDIT.\n\nimport "database/sql"\n\nvar _ sql.DB\n',
      );
      const files = (await verifySqlc(m.root, await m.files())).map((f) => f.file);
      expect(files).toContain("svc/internal/db/fakegen.go");
      expect(files).toContain("svc/internal/db/late.go");
    });

    test("an edited generated file is flagged", async () => {
      const m = await module();
      spawnSync("sqlc", ["generate"], { cwd: join(m.root, "svc") });
      const q = join(m.root, "svc/internal/db/queries.sql.go");
      await writeFile(q, `${await readFile(q, "utf8")}\nfunc Extra() {}\n`);
      const found = await verifySqlc(m.root, await m.files());
      expect(found.map((f) => f.message).join()).toContain("differs from sqlc generate output");
    });

    test("configs with plugins are refused", async () => {
      const m = await module();
      spawnSync("sqlc", ["generate"], { cwd: join(m.root, "svc") });
      await writeFile(
        join(m.root, "svc/sqlc.yaml"),
        `${CONFIG}plugins:\n  - name: evil\n    process:\n      cmd: sh\n`,
      );
      const found = await verifySqlc(m.root, await m.files());
      expect(found[0]?.message).toContain("plugins");
    });
  },
);

describe("without sqlc", () => {
  test("external input references cannot read host files during regeneration", async () => {
    const fixture = await module();
    await writeFile(
      join(fixture.root, "svc/sqlc.yaml"),
      CONFIG.replace("internal/db/schema.sql", "/outside/schema.sql"),
    );
    expect((await verifySqlc(fixture.root, await fixture.files()))[0]?.message).toContain(
      "outside isolated repository",
    );
  });
  test("a forged header without a config fails closed", async () => {
    const root = await mkdtemp(join(tmpdir(), "matrix-sqlc-forged-"));
    await mkdir(join(root, "services/storage/internal/db"), { recursive: true });
    const file = "services/storage/internal/db/forged.go";
    await writeFile(join(root, file), "package db\n// Code generated by sqlc. DO NOT EDIT.\n");
    expect(await verifySqlc(root, [file])).toEqual([
      { file, message: "internal/db has no verifiable sqlc output configuration" },
    ]);
  });
  test("committed generated code fails as unverifiable", async () => {
    const m = await module();
    await writeFile(join(m.root, "svc/internal/db/db.go"), "package db\n");
    const PATH = process.env.PATH;
    process.env.PATH = "/nonexistent";
    try {
      const found = await verifySqlc(m.root, await m.files());
      expect(found[0]?.message).toContain("cannot be verified");
    } finally {
      process.env.PATH = PATH;
    }
  });
});
