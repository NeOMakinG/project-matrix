import { z } from "zod";

export const SignalProvider = z.enum(["sentry", "glitchtip", "posthog", "otel", "uptime"]);
export type SignalProvider = z.infer<typeof SignalProvider>;

export const SignalLevel = z.enum(["fatal", "error", "warning", "info"]);
export type SignalLevel = z.infer<typeof SignalLevel>;

export const StackFrame = z.object({
  file: z.string(),
  function: z.string().optional(),
  line: z.number().int().optional(),
  inApp: z.boolean(),
});
export type StackFrame = z.infer<typeof StackFrame>;

/** One production occurrence (or alert), normalized across providers. */
export const Signal = z.object({
  id: z.string(),
  provider: SignalProvider,
  projectId: z.string(),
  kind: z.enum(["error", "alert", "downtime"]),
  title: z.string(),
  message: z.string(),
  level: SignalLevel,
  occurredAt: z.iso.datetime({ offset: true }),
  release: z.string().optional(),
  environment: z.string().optional(),
  exceptionType: z.string().optional(),
  providerFingerprint: z.string().optional(),
  frames: z.array(StackFrame),
  /**
   * How far the content can be trusted. `client`: sent by browser/mobile SDKs or public capture keys,
   * so anyone can forge it. `server`: server SDK from a project configured as server-only.
   * `infra`: generated by our own monitoring (alert rules, uptime checks).
   */
  trust: z.enum(["client", "server", "infra"]),
  /** Hashed user ids seen in this signal (never raw ids). */
  userHashes: z.array(z.string()),
  /** Distinct users the provider reports for the whole issue (0 when unknown). */
  reportedUsers: z.number().int().nonnegative(),
  count: z.number().int().positive(),
  url: z.string().optional(),
});
export type Signal = z.infer<typeof Signal>;

/**
 * Raw signal envelope as stored by the server's webhook endpoints
 * (structurally compatible with the server's MonitorSignal) or produced by pollers.
 */
export interface RawSignal {
  source: SignalProvider | "github";
  kind: string;
  projectId?: string;
  fingerprint?: string;
  title: string;
  payload: unknown;
  receivedAt: string;
}

/** Port: where raw signals come from (server store, pollers, tests). */
export interface SignalSource {
  pull(since: string): Promise<RawSignal[]>;
  /** Errors from sub-sources that failed while others succeeded (reported, then cleared). */
  drainErrors?(): string[];
}
